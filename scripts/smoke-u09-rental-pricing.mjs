import assert from "node:assert/strict";
import {calculateRentalPrice,rentalQuoteMatches} from "../lib/rentalPricing.mjs";
import {readFileSync} from "node:fs";
const item={dailyPriceOre:50000,weekendPriceOre:120000,weeklyPriceOre:250000,depositOre:100000,longTermDays:14,longTermDiscountPercent:10};
const calc=(a,b,extra={})=>calculateRentalPrice({...item,...extra},a,b);
assert.equal(calc("2026-11-25","2026-11-25").totalOre,50000);
assert.equal(calc("2026-11-27","2026-11-29").totalOre,120000);
assert.equal(calc("2026-11-23","2026-11-29").totalOre,250000);
assert.equal(calc("2026-11-23","2026-11-30").totalOre,300000);
assert.equal(calc("2026-11-23","2026-11-29",{weeklyPriceOre:400000}).totalOre,350000);
assert.equal(calc("2026-11-23","2026-12-06").totalOre,450000);
assert.equal(calc("2026-11-23","2026-12-06").discountOre,50000);
assert.equal(calc("2026-11-27","2026-11-29",{weekendPriceOre:0}).totalOre,150000);
assert.equal(calc("2026-11-25","2026-11-25",{dailyPriceOre:50001}).totalOre,50001);
assert.equal(calc("2026-11-25","2028-11-25"),null);
assert.equal(calc("2026-11-25","2026-11-25",{dailyPriceOre:0}),null);
assert.equal(calc("2026-11-25","2026-11-25").depositOre,100000);
const p=calc("2026-11-25","2026-11-25");
assert.ok(rentalQuoteMatches({totalOre:50000,depositOre:100000},p));
assert.ok(!rentalQuoteMatches({totalOre:50000,depositOre:99999},p));
assert.ok(!rentalQuoteMatches(null,p));
const post=readFileSync("app/api/rental-bookings/route.js","utf8");
assert.ok(post.indexOf("rentalQuoteMatches(b.expectedPricing,p)")<post.indexOf('s.rpc("create_rental_booking_if_available"'));
assert.ok(readFileSync("app/api/rental/route.js","utf8").includes("calculateRentalPrice(item,start,end)"));
console.log("U-09 shared pricing and price confirmation tests passed.");
