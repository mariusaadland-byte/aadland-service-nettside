import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const load=p=>readFileSync(p,"utf8");
const source=load("lib/rentalDepositReview.js").replace(/^export /gm,"");
const {validateRentalDepositInspection}=new Function(source+";return {validateRentalDepositInspection};")();
const booking={status:"returned",deposit_ore:250000};
assert.ok(validateRentalDepositInspection({...booking,status:"active"},{result:"ok",damageEstimateOre:0}).error);
assert.ok(validateRentalDepositInspection({status:"returned",deposit_ore:0},{result:"ok",damageEstimateOre:0}).error);
assert.deepEqual(validateRentalDepositInspection(booking,{result:"ok",damageEstimateOre:0,note:"Ser fint ut"}).value,{result:"ok",damage_estimate_ore:0,note:"Ser fint ut"});
assert.ok(validateRentalDepositInspection(booking,{result:"ok",damageEstimateOre:100}).error);
assert.ok(validateRentalDepositInspection(booking,{result:"damage",damageEstimateOre:250001,note:"Knust skjerm ved retur"}).error);
assert.ok(validateRentalDepositInspection(booking,{result:"damage",damageEstimateOre:1000,note:"Kort"}).error);
assert.equal(validateRentalDepositInspection(booking,{result:"damage",damageEstimateOre:50000,note:"Ripe ved håndtaket"}).value.damage_estimate_ore,50000);
const api=load("app/api/admin/rental-deposits/route.js");
assert.ok(api.includes('allowed("canUpdateOrders")'));
assert.ok(api.includes('allowed("canViewOrders")'));
assert.ok(api.includes("sameOriginGuard(req)"));
assert.ok(api.includes("rental_deposit_inspection_events"));
assert.ok(!api.includes("createVippsPayment")&&!api.includes("captureVippsPayment")&&!api.includes("refundVippsPayment"));
const sql=load("supabase/migrations/20261025202000_rental_deposit_inspection_audit.sql");
assert.ok(sql.includes("enable row level security"));
assert.ok(sql.includes("revoke all on table"));
assert.ok(sql.includes("from service_role"));
const mobile=load("app/admin/mobil/page.js");
assert.ok(mobile.includes('href:"/admin/utleie/depositum"'));
console.log("Returkontroll: validering, full historikk, serverrettigheter og betalingsskille OK.");
