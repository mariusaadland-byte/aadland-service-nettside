import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {rentalPortalExpired,rentalPortalGroup,rentalPortalCanPay,rentalPortalOverdue,rentalPortalDeposit} from "../lib/rentalCustomerPortal.mjs";
const at=Date.parse("2026-11-25T12:00:00Z");
const r={status:"new",payment_status:"unpaid",paymentDetailsAvailable:true,total_ore:10000,payment_due_at:"2026-11-25T11:00:00Z"};
assert.ok(rentalPortalExpired(r,at));
assert.equal(rentalPortalGroup(r,at),"history");
assert.equal(rentalPortalCanPay(r,true,at),false);
assert.equal(rentalPortalGroup({...r,status:"active",end_date:"2026-11-24"},at),"active");
assert.ok(rentalPortalOverdue({...r,status:"active",end_date:"2026-11-24"},"2026-11-25"));
assert.equal(rentalPortalGroup({...r,status:"returned"},at),"settlement");
assert.equal(rentalPortalCanPay({...r,payment_due_at:null},true,at),true);
assert.equal(rentalPortalCanPay({...r,payment_due_at:null,paymentDetailsAvailable:false},true,at),false);
assert.equal(rentalPortalCanPay({...r,status:"active"},true,at),false);
assert.equal(rentalPortalCanPay({...r,status:"confirmed",payment_captured_ore:1000},true,at),false);
assert.deepEqual(rentalPortalDeposit({deposit_held_ore:200000,deposit_charged_ore:50000}),{held:200000,used:50000,rest:150000,closed:false});
const me=readFileSync("app/api/customer/me/route.js","utf8");
const vipps=readFileSync("app/api/customer/rental-vipps/route.js","utf8");
assert.ok(me.includes('.eq("customer_user_id",customer.id)'));
assert.ok(vipps.includes('.eq("customer_user_id",customerUserId)'));
assert.ok(me.includes("private, no-store"));
console.log("U-12 rental portal classification, payment eligibility, deposit and owner scope assertions passed.");
