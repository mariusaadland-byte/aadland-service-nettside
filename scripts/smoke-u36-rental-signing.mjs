import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {rentalSigningReview,rentalSigningInput,rentalSignatureSummary,RENTAL_SIGNING_VERSION} from "../lib/rentalSigning.mjs";
import {rentalAccessoryRecord} from "../lib/rentalAccessories.mjs";
import {rentalHandoverChecklist} from "../lib/rentalHandover.mjs";
const booking={id:"test",bookingNumber:"test-1",itemName:"Testverktøy",startDate:"2026-11-27",endDate:"2026-11-28",customer:{}};
const a=rentalAccessoryRecord(booking,"active",{confirmed:true,rows:[{name:"Batteri",quantity:2}]},"test");
const control={checks:Object.fromEntries(rentalHandoverChecklist("active").map(([k])=>[k,true])),note:"",deviation:false};
const review=rentalSigningReview(booking,"active",a,control),input={name:"Test Kunde",agreed:true,witnessed:true,review:JSON.stringify(review)};
assert.ok(rentalSigningInput(review,input));
assert.equal(rentalSigningInput(review,{...input,witnessed:false}),null);
assert.equal(rentalSigningInput(review,{...input,name:""}),null);
assert.equal(rentalSigningInput({...review,note:"Endret"},input),null);
assert.equal(rentalSigningReview(booking,"active",a,{checks:{}}),null);
assert.deepEqual(rentalSignatureSummary({active:{version:RENTAL_SIGNING_VERSION,name:"Test Kunde",recordedAt:"test",digest:"abc",review:{private:"test"}}}),{active:{name:"Test Kunde",recordedAt:"test",method:"typed_in_person",digest:"abc"}});
const api=readFileSync("app/api/admin/rental-bookings/route.js","utf8");
assert.ok(api.includes('process.env.RENTAL_SIGNING_ENABLED==="true"')&&api.includes("changes.handover_signatures")&&api.includes("rentalSigningInput(review,b.signature)")&&api.includes('createHash("sha256")'));
assert.ok(api.includes('.eq("updated_at",current.updated_at)')&&api.includes("signatures:rentalSignatureSummary"));
assert.ok(!readFileSync("app/api/customer/me/route.js","utf8").includes("handover_signatures"));
console.log("U-36 typed witness signature, exact review matching and private summary safeguards passed.");
