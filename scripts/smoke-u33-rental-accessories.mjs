import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {rentalAccessoryRecord,rentalAccessoryBaseline} from "../lib/rentalAccessories.mjs";
const at="2026-11-27T12:00:00Z",b={customer:{name:"Test",pickupTime:"09:00"}};
const a=rentalAccessoryRecord(b,"active",{confirmed:true,rows:[{name:"Batteri",quantity:2},{name:"Lader",quantity:1}]},at);
assert.equal(a.customer.pickupTime,"09:00");
assert.equal(rentalAccessoryBaseline(a.customer).length,2);
assert.ok(rentalAccessoryRecord(b,"active",{confirmed:true,rows:[]},at).error);
assert.ok(rentalAccessoryRecord(b,"active",{confirmed:true,rows:[{name:"Batteri",quantity:2},{name:"batteri",quantity:1}]},at).error);
assert.ok(rentalAccessoryRecord(b,"active",{confirmed:true,rows:[{name:"Batteri",quantity:null}]},at).error);
assert.ok(rentalAccessoryRecord(b,"active",{confirmed:true,rows:[],noAccessories:true},at).customer);
const rows=[{name:"Batteri",returned:1,damaged:1},{name:"Lader",returned:1,damaged:0}];
const ret=rentalAccessoryRecord({customer:a.customer},"returned",{confirmed:true,rows},at);
assert.equal(ret.deviation,true);assert.equal(ret.customer.accessoryReturn.rows[0].missing,1);
assert.ok(rentalAccessoryRecord({customer:a.customer},"returned",{confirmed:true,rows:[{...rows[0],returned:3},rows[1]]},at).error);
assert.ok(rentalAccessoryRecord({customer:a.customer},"returned",{confirmed:true,rows:[{...rows[0],damaged:2},rows[1]]},at).error);
assert.ok(rentalAccessoryRecord({customer:a.customer},"returned",{confirmed:true,rows:[]},at).error);
assert.ok(rentalAccessoryRecord(b,"returned",{confirmed:true,legacyReviewed:true},at).deviation);
assert.ok(rentalAccessoryRecord(b,"returned",{confirmed:true},at).error);
const api=readFileSync("app/api/admin/rental-bookings/route.js","utf8");
assert.ok(api.includes("rentalAccessoryRecord(current,b.status,b.accessories,now)")&&api.includes("changes.customer=accessory.customer")&&api.includes("accessory.deviation&&String"));
assert.ok(api.includes("rentalHandoverRecord(current,b.status,b.handoverChecklist,now)")&&api.includes('.eq("updated_at",current.updated_at)'));
console.log("U-33 accessory counts, locked handover baseline, legacy return and same-update safeguards passed.");
