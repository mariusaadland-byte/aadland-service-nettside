import assert from "node:assert/strict";
import {filterRentalCatalog,rentalCatalogCategory,RENTAL_CATALOG_PAGE_SIZE} from "../lib/rentalCatalogFilter.mjs";
const categories=[{id:"a",name:"Sag"},{id:"b",name:"Boring"}];
const items=Array.from({length:25},(_,i)=>({id:i,name:i===0?"Milwaukee borsag":i===1?"Makita støvsuger":"Verktøy "+i,description:i===0?"Batteri 18V":i===1?"Støvavsug":"",categoryId:i%2?"b":"a",dailyPriceOre:(25-i)*100}));
items.push({id:25,name:"Ukategorisert",categoryId:"old",dailyPriceOre:100});
assert.equal(filterRentalCatalog(items,categories).length,26);
assert.equal(filterRentalCatalog(items,categories).slice(0,RENTAL_CATALOG_PAGE_SIZE).length,12);
assert.equal(filterRentalCatalog(items,categories).slice(0,2*RENTAL_CATALOG_PAGE_SIZE).length,24);
assert.equal(new Set(filterRentalCatalog(items,categories).map(x=>x.id)).size,26);
assert.deepEqual(filterRentalCatalog(items,categories,{query:"  MILWAUKEE 18v "}).map(x=>x.id),[0]);
assert.deepEqual(filterRentalCatalog(items,categories,{query:"stovsuger"}).map(x=>x.id),[1]);
assert.deepEqual(filterRentalCatalog(items,categories,{query:"makita",category:"a"}),[]);
assert.deepEqual(filterRentalCatalog(items,categories,{category:"uncategorized"}).map(x=>x.id),[25]);
assert.equal(rentalCatalogCategory(items[25],categories),"uncategorized");
assert.equal(filterRentalCatalog(items,categories,{query:"boring"}).length,12);
assert.equal(filterRentalCatalog(items,categories,{sort:"price-asc"})[0].dailyPriceOre,100);
assert.equal(filterRentalCatalog(items,categories,{sort:"price-desc"})[0].id,0);
assert.equal(filterRentalCatalog(items,categories,{query:"finnesikke"}).length,0);
console.log("U-05 katalog: full produktliste, paginering, søk, sortering og kategorier bestått.");
