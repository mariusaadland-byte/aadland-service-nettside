import assert from "node:assert/strict";
import {groupReservationInput,groupReservationPlan,reservationReplay} from "../lib/rentalGroupReservation.mjs";
import {groupQuoteSnapshot} from "../lib/rentalGroupQuote.mjs";
import {RENTAL_TERMS_VERSION} from "../lib/rentalTermsVersion.mjs";
const id="00000000-0000-4000-8000-000000000001",id2="00000000-0000-4000-8000-000000000002",goodsId="00000000-0000-4000-8000-000000000003",requestId="00000000-0000-4000-8000-000000000004",today="2026-11-27";
const a={itemId:id,name:"Borhammer",startDate:today,endDate:"2026-11-28",quantity:2,available:true,totalOre:120000,depositOre:300000},b={...a,itemId:id2,name:"Sliper",quantity:1,totalOre:40000,depositOre:50000},g={id:goodsId,name:"Bor",sku:"B8",quantity:2,unitOre:7900};
const q=groupQuoteSnapshot({rentals:[b,a],goods:[g],today});
const body={requestId,quoteDigest:q.digest,acceptedTerms:true,termsVersion:RENTAL_TERMS_VERSION,lines:[b,a],consumables:[g],totalOre:1,customerId:"untrusted"};
const input=groupReservationInput(body,today);
assert.equal(input.customerId,undefined);assert.equal(input.totalOre,undefined);
const plan=groupReservationPlan({input,serverRentals:[a,b],serverGoods:[g],today});
assert.equal(plan.units.length,3);assert.equal(plan.units.reduce((s,u)=>s+u.totalOre,0),160000);
assert.equal(plan.snapshot.payableOre,175800);assert.equal(plan.snapshot.depositOre,350000);
assert.deepEqual(plan.itemLocks,[id,id2]);
assert.equal(groupReservationPlan({input,serverRentals:[{...a,totalOre:120002},b],serverGoods:[g],today}),null);
assert.equal(groupReservationPlan({input,serverRentals:[{...a,available:false},b],serverGoods:[g],today}),null);
assert.equal(groupReservationInput({...body,acceptedTerms:false},today),null);
assert.equal(groupReservationInput({...body,lines:[a,a]},today),null);
assert.equal(groupReservationPlan({input:{...input,goods:[]},serverRentals:[a,b],serverGoods:[g],today}),null);
const existing={customerId:"a",requestId,quoteDigest:q.digest};
assert.equal(reservationReplay(existing,existing),"same");assert.equal(reservationReplay(existing,{...existing,customerId:"b"}),"conflict");
console.log("U-37E group reservation plan and replay checks passed");
