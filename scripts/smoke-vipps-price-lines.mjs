import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const source=readFileSync('lib/vippsPriceLines.js','utf8').replace(/export /g,'');
const {total,adjust}=new Function(source+';return {total:customerTotalOre,adjust:linesForCustomerTotal};')();
const lines=[{id:'m',type:'material',description:'Material',quantity:2,unitPriceOre:10000,vatRate:25,internalUnitCostOre:5000},{id:'w',type:'work',description:'Arbeid',quantity:1,unitPriceOre:60000,vatRate:25}];
assert.equal(total(lines),100000);
const changed=adjust(lines,103185);
assert.ok(changed.totalOre>=103185);
assert.ok(changed.totalOre-103185<=2);
assert.equal(changed.adjustedLineIndex,1);
assert.equal(changed.lineItems[0].unitPriceOre,10000,'Do not change material pricing');
assert.equal(changed.lineItems[0].internalUnitCostOre,5000,'Private cost unchanged');
assert.equal(total(lines),100000,'No mutation');
const again=adjust(changed.lineItems,103185);
assert.equal(again.totalOre,changed.totalOre,'Reapplying an exact target must not increase a previous gross-up');
assert.equal(adjust([],1000),null);
assert.equal(adjust([{type:'work',quantity:1,unitPriceOre:'',vatRate:25}],1000),null);
assert.equal(adjust(lines,1),null,'Never make unrelated lines negative');
console.log('Vipps customer pricing lines: VAT, repeat application, no additional line, no price mutation passed.');
