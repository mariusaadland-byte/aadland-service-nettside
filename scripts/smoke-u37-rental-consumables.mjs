import assert from "node:assert/strict";
import {consumableInput,consumableQuote,mixedQuoteTotals} from "../lib/rentalConsumables.mjs";
const id="00000000-0000-4000-8000-000000000001",tool="00000000-0000-4000-8000-000000000002",other="00000000-0000-4000-8000-000000000003";
const p={id,name:"Bor",rental_item_id:tool,active:true,stock_quantity:5,price_ore:7900,cost_ore:3000};
const x={id,quantity:2,price_ore:1};
assert.deepEqual(consumableInput(undefined),[]);
assert.equal(consumableInput(null),null);
assert.equal(consumableInput([x,x]),null);
assert.equal(consumableInput([{...x,quantity:-1}]),null);
assert.equal(consumableInput([{...x,quantity:1.5}]),null);
const q=consumableQuote([x],[p],[tool]);assert.equal(q.salesOre,15800);
assert.equal(q.lines[0].cost_ore,undefined);
assert.equal(consumableQuote([x],[p],[other]).salesOre,null);
assert.equal(consumableQuote([{...x,quantity:6}],[p],[tool]).salesOre,null);
assert.equal(consumableQuote([x],[{...p,active:false}],[tool]).salesOre,null);
assert.equal(consumableQuote([x],[{...p,price_ore:2147483647}],[tool]).salesOre,null);
assert.deepEqual(mixedQuoteTotals({rentalOre:60000,depositOre:150000,quantity:1},q),{rentalOre:60000,depositOre:150000,quantity:1,salesOre:15800,payableOre:75800});
assert.equal(mixedQuoteTotals({rentalOre:2147483647,depositOre:0},q),null);
console.log("U-37 consumables validation, price authority, stock and separate deposit passed");
