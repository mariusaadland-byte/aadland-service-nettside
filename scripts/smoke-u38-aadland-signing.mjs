import assert from "node:assert/strict";
import {agreementDocumentDigest,issueSigningChallenge,verifySigningCode,signingConsent,sealSigningEvidence,signingEvidenceIntact} from "../lib/aadlandSigning.mjs";
const key=Buffer.alloc(32,7),now="2026-11-27T12:00:00Z";
const expected={agreementId:"00000000-0000-4000-8000-000000000001",customerId:"00000000-0000-4000-8000-000000000002",email:"demo@example.invalid",documentDigest:agreementDocumentDigest(Buffer.from("Synthetic agreement")),quoteDigest:"a".repeat(64),termsVersion:"2026-11-25"};
const {code,challenge}=issueSigningChallenge({...expected,now,key});
assert.match(code,/^\d{6}$/);assert.equal(challenge.code,undefined);
const v={challenge,expected,code,now,key};
assert.equal(verifySigningCode(v),"verified");
assert.equal(verifySigningCode({...v,code:code==="000000"?"000001":"000000"}),"wrong_code");
assert.equal(verifySigningCode({...v,now:"2026-11-27T12:10:00Z"}),"expired");
assert.equal(verifySigningCode({...v,challenge:{...challenge,attempts:5}}),"locked");
assert.equal(verifySigningCode({...v,challenge:{...challenge,state:"consumed"}}),"closed");
assert.equal(verifySigningCode({...v,expected:{...expected,email:"other@example.invalid"}}),"review");
assert.equal(verifySigningCode({...v,expected:{...expected,documentDigest:"b".repeat(64)}}),"review");
const consent=signingConsent({...expected,accepted:true,paymentObligation:true,name:"Test Kunde"},expected);
assert.equal(signingConsent({...expected,accepted:true,name:"Test Kunde"},expected),null);
assert.equal(sealSigningEvidence({expected,challenge,consent,verifiedAt:now,key}),null);
const record=sealSigningEvidence({expected,challenge:{...challenge,state:"consumed"},consent,verifiedAt:now,key});
assert.equal(signingEvidenceIntact(record,key),true);
assert.equal(signingEvidenceIntact({...record,evidence:{...record.evidence,name:"Changed"}},key),false);
assert.equal(record.evidence.code,undefined);
console.log("U-38 signing challenge, document binding and evidence integrity tests passed");
