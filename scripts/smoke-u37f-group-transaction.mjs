import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {GROUP_HOLD_MINUTES,groupExpiryDecision} from "../lib/rentalGroupExpiry.mjs";
const x={status:"held",expiresAt:"2026-11-27T12:30:00Z",now:"2026-11-27T12:30:00Z",paymentReference:null,paymentStarted:false,childrenSafe:true};
assert.equal(GROUP_HOLD_MINUTES,30);
assert.equal(groupExpiryDecision(x),"release_once");
assert.equal(groupExpiryDecision({...x,now:"2026-11-27T12:29:59Z"}),"keep");
assert.equal(groupExpiryDecision({...x,paymentReference:"vipps-ref"}),"keep");
assert.equal(groupExpiryDecision({...x,paymentStarted:true}),"keep");
assert.equal(groupExpiryDecision({...x,status:"payment_pending"}),"keep");
assert.equal(groupExpiryDecision({...x,status:"released"}),"no_change");
assert.equal(groupExpiryDecision({...x,childrenSafe:false}),"review");
assert.equal(groupExpiryDecision({...x,expiresAt:"invalid"}),"review");
const sql=readFileSync("docs/u37f-group-transaction.draft.sql","utf8");
assert.match(sql,/pg_advisory_xact_lock\(hashtext\(item_uuid::text\)\)/);
assert.match(sql,/reserved_quantity=reserved_quantity\+n/);
assert.match(sql,/reserved_quantity=reserved_quantity-r.quantity/);
assert.match(sql,/rollback;\s*$/);
assert.match(sql,/revoke all on function public.draft_group_expire\(uuid\) from public,anon,authenticated,service_role/);
console.log("U-37F expiry decision and SQL draft structure passed (not a database integration test)");
