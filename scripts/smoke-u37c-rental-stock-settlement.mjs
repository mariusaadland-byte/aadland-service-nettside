import assert from "node:assert/strict";
import {saleSnapshot,stockTransition,rentalSalesInvoiceDraft} from "../lib/rentalStockSettlement.mjs";
const id="00000000-0000-4000-8000-000000000001",orderId="00000000-0000-4000-8000-000000000002";
const g={id,name:"Bor",sku:"B8",quantity:2,unitOre:7900,totalOre:1};
assert.equal(saleSnapshot([g]).grossOre,15800);
assert.equal(saleSnapshot([g,g]),null);
const reserve=stockTransition({state:"none",event:"reserve",quantity:2,onHand:5,reserved:1});
assert.deepEqual(reserve,{state:"held",onHand:5,reserved:3,changed:true});
assert.equal(stockTransition({state:"none",event:"reserve",quantity:5,onHand:5,reserved:1}),null);
assert.equal(stockTransition({...reserve,event:"reserve",quantity:2}).changed,false);
const confirmed=stockTransition({...reserve,event:"confirm",quantity:2});
assert.equal(confirmed.reserved,3);
const fulfilled=stockTransition({...confirmed,event:"fulfill",quantity:2});
assert.deepEqual(fulfilled,{state:"fulfilled",onHand:3,reserved:1,changed:true});
assert.equal(stockTransition({...fulfilled,event:"fulfill",quantity:2}).changed,false);
assert.equal(stockTransition({...fulfilled,event:"release",quantity:2}),null);
const cancelled=stockTransition({...reserve,event:"release",quantity:2});
assert.deepEqual(cancelled,{state:"released",onHand:5,reserved:1,changed:true});
assert.equal(stockTransition({...cancelled,event:"confirm",quantity:2}),null);
assert.equal(stockTransition({...reserve,event:"fulfill",quantity:2}),null);
const d=rentalSalesInvoiceDraft({orderId,rentalLines:[{description:"Leie borhammer",grossOre:60000,quantity:1}],goods:[g],depositOre:150000});
assert.equal(d.grossOre,75800);assert.equal(d.netOre,60640);assert.equal(d.vatOre,15160);assert.equal(d.depositOre,150000);assert.equal(d.readyToPost,false);
console.log("U-37C reservation transitions and draft invoice tests passed");
