import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
import {parseRentalWindows,validRentalWindow,rentalWindowChoices,validateRentalWindowRequest,rentalWindowConfig,rentalWindowSummary} from "../lib/rentalPickupWindows.mjs";
assert.ok(validRentalWindow("09:00-10:00"));assert.ok(!validRentalWindow("10:00-09:00"));assert.ok(!validRentalWindow("24:00-25:00"));
const p=parseRentalWindows('{"thu":["09:00-10:00","12:00-13:00"]}'),r=parseRentalWindows('{"thu":["15:00-16:00"]}');
assert.equal(parseRentalWindows('{"thu":["09:00-11:00","10:00-12:00"]}'),null);
assert.deepEqual(rentalWindowChoices(p,"2026-11-26","2026-11-26T10:00"),["12:00-13:00"]);
const c={enabled:true,pickup:p,return:r},b={pickupWindow:"09:00-10:00",returnWindow:"15:00-16:00"};
const v=validateRentalWindowRequest(b,c,"pickup","2026-11-26","2026-11-26","2026-11-25T10:00");
assert.ok(v&&rentalWindowSummary(v).includes("må avtales"));
assert.equal(validateRentalWindowRequest(b,c,"pickup","2026-11-27","2026-11-27",""),null);
assert.equal(validateRentalWindowRequest(b,c,"pickup","2026-11-26","2026-11-26","2026-11-26T09:00"),null);
assert.equal(validateRentalWindowRequest(b,c,"delivery","2026-11-26","2026-11-26",""),null);
assert.deepEqual(validateRentalWindowRequest({},rentalWindowConfig({}),"pickup","2026-11-26","2026-11-26",""),{});
assert.equal(validateRentalWindowRequest(b,{enabled:true,pickup:r,return:p},"pickup","2026-11-26","2026-11-26",""),null);
const api=readFileSync("app/api/rental-bookings/route.js","utf8");assert.ok(api.includes("validateRentalWindowRequest")&&api.includes("siteOrigin,...windows"));
assert.ok(readFileSync("app/api/admin/rental/manual-booking/route.js","utf8").includes("rentalWindowConfig(process.env)"));
assert.ok(readFileSync("lib/rentalConfirmationEmail.js","utf8").includes("rentalWindowSummary"));
console.log("U-32 rental pickup window validation and request display passed.");
