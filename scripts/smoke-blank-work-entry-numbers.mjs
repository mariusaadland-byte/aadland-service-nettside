const readiness=src("lib/invoiceIssueInputReadiness.js");
const check=new Function(readiness.replace(/^export /gm,"")+";return invoiceIssueInputError;")();
const base={line_items:[{description:"Arbeid",type:"work",quantity:null,unit:"stk",unitPriceOre:null,vatRate:25}]};
assert.match(check(base),/antall eller timer/);
assert.match(check({...base,line_items:[{...base.line_items[0],quantity:2}]}),/pris eks/);
assert.equal(check({...base,line_items:[{...base.line_items[0],quantity:2,unitPriceOre:50000}]}),null);
assert.match(check({...base,line_items:[{...base.line_items[0],quantity:2,unitPriceOre:0}]}),/beløp større enn 0/);
assert.equal(check({...base,line_items:[{...base.line_items[0],quantity:2,unitPriceOre:50000},
 {description:"Gratis ekstra",quantity:1,unitPriceOre:0,vatRate:25}]}),null);
assert.ok(invoiceApi.includes('quantity:null,unit:"stk",unitPriceOre:null,vatRate:25'));
assert.ok(invoiceApi.includes('quantity:x.quantity==null||x.quantity===""?null:Number(x.quantity)'));
assert.ok(invoiceApi.includes('unitPriceOre:x.unitPriceOre==null||x.unitPriceOre===""?null:Number(x.unitPriceOre)'));
assert.ok(invoice.includes('value={l.quantity??""}'));
assert.ok(invoice.includes('value={l.unitPriceOre==null?"":Number(l.unitPriceOre)/100}'));
assert.ok(invoice.includes('quantity:null,unit:"stk",unitPriceOre:null,vatRate:25,type:"work"'));
assert.ok(invoice.includes('invoiceIssueInputError(form)'));
for(const route of [issue,send,vipps])assert.ok(route.includes('invoiceIssueInputError(invoice)'));
assert.ok(quote.includes('description:"",quantity:"",unit:"time",unitPriceOre:"",vatRate:25'));
assert.ok(quote.includes('id:lineId(),type,description:"",quantity:""'));
assert.ok(quote.includes('description:consumablePrefix,quantity:"",unit:"stk"'));
assert.ok(quote.includes('if(v.lineItems.some(line=>!Number.isFinite(Number(line.quantity))||Number(line.quantity)<=0))'));
assert.ok(quote.includes('vatRate:25'));
assert.ok(clock.includes('const DEFAULT_RATE=""'));
assert.ok(clock.includes('const DEFAULT_KM_RATE=""'));
