import assert from "node:assert/strict";
import {readFileSync} from "node:fs";
const src=p=>readFileSync(p,"utf8");
const invoice=src("app/admin/faktura/InvoicesClient.js");
const invoiceApi=src("app/api/admin/invoices/route.js");
const issue=src("app/api/admin/invoices/issue/route.js");
const send=src("app/api/admin/invoices/send/route.js");
const vipps=src("lib/invoiceVipps.js");
const quote=src("app/admin/tilbud/QuoteEditorClient.js");
